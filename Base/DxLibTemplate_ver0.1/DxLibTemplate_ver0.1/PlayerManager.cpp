#include "PlayerManager.h"
#include "Player.h"
#include "ObjectManager.h"


//---------------------------------------------------------------------------------
//	プレイヤーマネージャーの処理
//---------------------------------------------------------------------------------


//---------------------------------------------------------------------------------
//	コンストラクタ
//---------------------------------------------------------------------------------
PlayerManager::PlayerManager()
{
	pPlayer = nullptr;
}

//---------------------------------------------------------------------------------
//	デストラクタ
//---------------------------------------------------------------------------------
PlayerManager::~PlayerManager()
{
	exit();
}


//---------------------------------------------------------------------------------
//	生成関数
//---------------------------------------------------------------------------------
void PlayerManager::playerGenerate()
{
	// プレイヤーの動的生成
	pPlayer = new Player(ObjectManager::getInstance()->generateId());
	ObjectManager::getInstance()->add(pPlayer);
}

void PlayerManager::exit()
{
	pPlayer = nullptr;
}